const LangCtx = createContext(null);
function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("tf:lang") || "fo");
  useEffect(() => {
    localStorage.setItem("tf:lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);
  const value = { lang, setLang, t: STRINGS[lang], toggle: () => setLang((l) => l === "fo" ? "en" : "fo") };
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}
function useT() {
  const ctx = useContext(LangCtx);
  if (!ctx) throw new Error("useT must be used inside LangProvider");
  return ctx;
}
function hoursLabel(t, oh) {
  if (!oh) return "";
  if (oh.kind === "always") return t.open247;
  if (oh.kind === "closedToday") return t.closedToday;
  return oh.range || "";
}
function pick(lang, v) {
  if (v && typeof v === "object" && ("fo" in v || "en" in v)) return v[lang] ?? v.fo ?? v.en ?? "";
  return v;
}
function LangToggle() {
  const { lang, setLang } = useT();
  return <div className="tf-langtoggle"><button className={lang === "fo" ? "on" : ""} onClick={() => setLang("fo")}>FO</button><button className={lang === "en" ? "on" : ""} onClick={() => setLang("en")}>EN</button></div>;
}
export {
  LangProvider,
  LangToggle,
  STRINGS,
  hoursLabel,
  pick,
  useT
};
